import { describe, expect, test } from 'vite-plus/test';

import { renderRuntimeRegistry, renderTypeRegistry } from './registry';
import { prepareSearchRoutes } from './route-config';

describe('search route registry', () => {
  const catalog = {
    id: 'catalog',
    file: '/project/src/routes/catalog.tsx',
    path: '/catalog',
    index: false,
  };
  const games = {
    id: 'games',
    file: '/project/src/routes/games.tsx',
    path: '/catalog/games',
    parentId: 'catalog',
    index: false,
  };
  const game = {
    id: 'game',
    file: '/project/src/routes/game.tsx',
    path: '/catalog/games/:gameId',
    parentId: 'games',
    index: false,
  };
  const preparedRoutes = prepareSearchRoutes([catalog, games, game], new Set(['catalog', 'game']));

  test('renders cumulative type augmentation from full route paths', () => {
    expect(
      renderTypeRegistry(
        preparedRoutes,
        '/project/.react-router-validated-search/types/registry.d.ts',
        'json',
      ),
    ).toContain("declare module 'react-router-validated-search'");

    expect(
      renderTypeRegistry(
        preparedRoutes,
        '/project/.react-router-validated-search/types/registry.d.ts',
        'json',
      ),
    ).toBe(
      `// Generated by react-router-validated-search. Do not edit.\n\nimport 'react-router-validated-search';\n\ndeclare module 'react-router-validated-search' {\n  interface SearchRouteRegistry {\n    "/catalog": readonly [typeof import("../../src/routes/catalog.js").validateSearch];\n    "/catalog/games": readonly [typeof import("../../src/routes/catalog.js").validateSearch];\n    "/catalog/games/:gameId": readonly [typeof import("../../src/routes/catalog.js").validateSearch, typeof import("../../src/routes/game.js").validateSearch];\n  }\n  interface SearchCodecRegister {\n    codec: "json";\n  }\n}\n`,
    );
  });

  test('renders root-to-target lazy validator chains', () => {
    expect(renderRuntimeRegistry(preparedRoutes)).toBe(
      `export const validatorImportsByRoutePattern = {\n  "/catalog": [() => import("/project/src/routes/catalog.tsx").then(module => module.validateSearch)],\n  "/catalog/games": [() => import("/project/src/routes/catalog.tsx").then(module => module.validateSearch)],\n  "/catalog/games/:gameId": [() => import("/project/src/routes/catalog.tsx").then(module => module.validateSearch), () => import("/project/src/routes/game.tsx").then(module => module.validateSearch)]\n};\n\nexport const validatorImportsByRouteId = {\n  "catalog": [() => import("/project/src/routes/catalog.tsx").then(module => module.validateSearch)],\n  "games": [() => import("/project/src/routes/catalog.tsx").then(module => module.validateSearch)],\n  "game": [() => import("/project/src/routes/catalog.tsx").then(module => module.validateSearch), () => import("/project/src/routes/game.tsx").then(module => module.validateSearch)]\n};\n`,
    );
  });

  test('uses the deepest matching route for a shared URL and keeps per-route chains', () => {
    const index = {
      id: 'catalog-index',
      file: '/project/src/routes/catalog-index.tsx',
      path: '/catalog',
      parentId: 'catalog',
      index: true,
    };
    const sharedPathRoutes = prepareSearchRoutes(
      [catalog, index],
      new Set(['catalog', 'catalog-index']),
    );

    expect(
      renderTypeRegistry(
        sharedPathRoutes,
        '/project/.react-router-validated-search/types/registry.d.ts',
      ),
    ).toContain(
      '"/catalog": readonly [typeof import("../../src/routes/catalog.js").validateSearch, typeof import("../../src/routes/catalog-index.js").validateSearch];',
    );
    expect(renderRuntimeRegistry(sharedPathRoutes)).toBe(
      `export const validatorImportsByRoutePattern = {\n  "/catalog": [() => import("/project/src/routes/catalog.tsx").then(module => module.validateSearch), () => import("/project/src/routes/catalog-index.tsx").then(module => module.validateSearch)]\n};\n\nexport const validatorImportsByRouteId = {\n  "catalog": [() => import("/project/src/routes/catalog.tsx").then(module => module.validateSearch)],\n  "catalog-index": [() => import("/project/src/routes/catalog.tsx").then(module => module.validateSearch), () => import("/project/src/routes/catalog-index.tsx").then(module => module.validateSearch)]\n};\n`,
    );
  });
});

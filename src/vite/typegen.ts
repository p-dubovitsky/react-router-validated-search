/**
 * Generation of shadow React Router `+types` and the typed route registry.
 *
 * @module
 */
import fs from 'node:fs/promises';
import path from 'node:path';

import { parseSync } from 'oxc-parser';

import { DEFAULT_SEARCH_CODEC, type SearchCodecName } from '../runtime/search-codec';
import { moduleSpecifier, renderTypeRegistry } from './registry';
import type { RouteRecord, PreparedSearchRoute } from './route-config';
import { collectPreparedSearchRoutes } from './scan-routes';

const SEARCH_TYPES = new Set([
  'LoaderArgs',
  'ActionArgs',
  'ClientLoaderArgs',
  'ClientActionArgs',
  'ComponentProps',
]);

type TypeAliasNode = {
  type: 'ExportNamedDeclaration';
  declaration?: {
    type: 'TSTypeAliasDeclaration';
    id: { name: string };
  } | null;
};

type NamespaceNode = {
  type: 'ExportNamedDeclaration';
  declaration?: {
    type: 'TSModuleDeclaration';
    id: { name: string };
    body?: { type: 'TSModuleBlock'; body: Array<TypeAliasNode> } | null;
  } | null;
};

/** Options shared by Vite-driven and CLI-driven type generation. */
export type GenerateSearchTypesOptions = {
  root: string;
  appDirectory: string;
  routes: ReadonlyArray<RouteRecord>;
  reactRouterTypesDirectory?: string;
  outputDirectory?: string;
  allowMissingReactRouterTypes?: boolean;
  codec?: SearchCodecName;
  /**
   * Routes the caller has already prepared. The Vite plugin scans route modules
   * anyway, so passing them here avoids reading and parsing every route file a
   * second time. The CLI omits them and scans on its own.
   */
  preparedRoutes?: ReadonlyArray<PreparedSearchRoute>;
};

/** Files and route records produced by one type-generation pass. */
export type GeneratedSearchTypes = {
  searchAwareRoutes: Array<RouteRecord>;
  files: Array<string>;
};

function routeTypeRelativePath(root: string, appDirectory: string, routeFile: string): string {
  const appRelative = path.relative(root, appDirectory);
  const routeRelative = path.relative(appDirectory, routeFile);
  const directory = path.dirname(routeRelative);
  const baseName = path.basename(routeRelative).replace(/\.[a-z0-9]+$/i, '');

  return path.join(appRelative, directory, '+types', `${baseName}.ts`);
}

function readRouteAliases(source: string, filename: string): Array<string> {
  const program = parseSync(filename, source, {
    lang: 'dts',
    astType: 'ts',
    sourceType: 'module',
  }).program;
  const body = program.body as Array<NamespaceNode>;
  const routeNamespace = body.find(
    (node) =>
      node.type === 'ExportNamedDeclaration' &&
      node.declaration?.type === 'TSModuleDeclaration' &&
      node.declaration.id.name === 'Route',
  )?.declaration;

  if (routeNamespace?.body?.type !== 'TSModuleBlock') {
    throw new Error(
      `[react-router-validated-search] Could not find exported Route namespace in ${filename}`,
    );
  }

  return routeNamespace.body.body.flatMap((node) =>
    node.declaration?.type === 'TSTypeAliasDeclaration' ? [node.declaration.id.name] : [],
  );
}

function renderShadowType(
  shadowFile: string,
  originalTypeFile: string,
  validatorFiles: ReadonlyArray<string>,
  aliases: ReadonlyArray<string>,
): string {
  const lines = aliases.map((name) =>
    SEARCH_TYPES.has(name)
      ? `  export type ${name} = ReactRouterRoute.${name} & { search: Search };`
      : `  export type ${name} = ReactRouterRoute.${name};`,
  );

  return (
    `// Generated by react-router-validated-search. Do not edit.\n\n` +
    `import type { InferValidatedSearchChain } from 'react-router-validated-search/internal';\n` +
    `import type { Route as ReactRouterRoute } from ${JSON.stringify(moduleSpecifier(shadowFile, originalTypeFile))};\n\n` +
    `type Search = InferValidatedSearchChain<readonly [${validatorFiles
      .map(
        (validatorFile) =>
          `typeof import(${JSON.stringify(moduleSpecifier(shadowFile, validatorFile))}).validateSearch`,
      )
      .join(', ')}]>;\n\n` +
    `export namespace Route {\n${lines.join('\n')}\n}\n`
  );
}

/**
 * Rewriting an unchanged file still bumps its mtime, which wakes up the
 * TypeScript watcher on every regeneration. Compare first.
 */
async function writeIfChanged(file: string, content: string): Promise<void> {
  try {
    if ((await fs.readFile(file, 'utf8')) === content) return;
  } catch {
    // Missing or unreadable — fall through and write it.
  }

  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, content);
}

/** What the previous generation pass recorded about itself. */
type Manifest = {
  files: Array<string>;
};

async function readManifest(manifestFile: string): Promise<Manifest> {
  let source: string;

  try {
    source = await fs.readFile(manifestFile, 'utf8');
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
      return { files: [] };
    }

    throw new Error(`Failed to read ${manifestFile}`, { cause: error });
  }

  try {
    const value = JSON.parse(source) as Partial<Manifest>;
    return { files: value.files ?? [] };
  } catch (error) {
    throw new Error(`Failed to read ${manifestFile}`, { cause: error });
  }
}

/**
 * Generate search-aware shadow types without modifying React Router output.
 *
 * The caller must run React Router typegen first unless missing originals are
 * explicitly allowed (used during early Vite lifecycle passes).
 */
export async function generateSearchTypes(
  options: GenerateSearchTypesOptions,
): Promise<GeneratedSearchTypes> {
  const reactRouterTypesDirectory =
    options.reactRouterTypesDirectory ?? path.join(options.root, '.react-router/types');
  const generatedRoot =
    options.outputDirectory ?? path.join(options.root, '.react-router-validated-search');
  const outputTypesDirectory = path.join(generatedRoot, 'types');
  const manifestFile = path.join(generatedRoot, 'manifest.json');
  const previous = await readManifest(manifestFile);
  const codec = options.codec ?? DEFAULT_SEARCH_CODEC;
  const preparedRoutes =
    options.preparedRoutes ?? (await collectPreparedSearchRoutes(options.routes));
  const searchAwareRoutes = preparedRoutes.map(({ route }) => route);

  // One route's types do not depend on another's, so they are read, rendered
  // and written concurrently; the manifest keeps route order regardless.
  const writtenShadowFiles = await Promise.all(
    preparedRoutes.map(async ({ route, validators }) => {
      const relativeTypeFile = routeTypeRelativePath(
        options.root,
        options.appDirectory,
        route.file,
      );
      const originalTypeFile = path.join(reactRouterTypesDirectory, relativeTypeFile);
      const shadowFile = path.join(outputTypesDirectory, relativeTypeFile);
      let originalTypeSource: string;
      try {
        originalTypeSource = await fs.readFile(originalTypeFile, 'utf8');
      } catch (error) {
        if (
          options.allowMissingReactRouterTypes &&
          error instanceof Error &&
          'code' in error &&
          error.code === 'ENOENT'
        ) {
          return undefined;
        }

        throw error;
      }

      const aliases = readRouteAliases(originalTypeSource, originalTypeFile);

      await writeIfChanged(
        shadowFile,
        renderShadowType(
          shadowFile,
          originalTypeFile,
          validators.map(({ file }) => file),
          aliases,
        ),
      );

      return path.relative(generatedRoot, shadowFile);
    }),
  );
  const files = writtenShadowFiles.filter((file) => file !== undefined);

  const registryFile = path.join(outputTypesDirectory, 'registry.d.ts');
  await writeIfChanged(registryFile, renderTypeRegistry(preparedRoutes, registryFile, codec));
  files.push(path.relative(generatedRoot, registryFile));

  const currentFiles = new Set(files);
  const staleFiles = previous.files.filter((file) => !currentFiles.has(file));

  await Promise.all(
    staleFiles.map((staleFile) => {
      const absoluteFile = path.resolve(generatedRoot, staleFile);
      if (!absoluteFile.startsWith(`${path.resolve(generatedRoot)}${path.sep}`)) {
        throw new Error(
          `[react-router-validated-search] Refusing to remove generated file outside ${generatedRoot}`,
        );
      }

      return fs.rm(absoluteFile, { force: true });
    }),
  );

  await fs.mkdir(generatedRoot, { recursive: true });
  const manifest: Manifest = { files };
  await fs.writeFile(manifestFile, `${JSON.stringify(manifest, null, 2)}\n`);

  return { searchAwareRoutes, files };
}
